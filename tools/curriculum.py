# ── 검증 ────────────────────────────────────────────────────────────────
ids = [c[0] for c in CARDS]
order = {cid: i for i, cid in enumerate(ids)}
errs = []
if len(ids) != len(set(ids)):
    errs.append("중복 id 존재")
for cid, _, qt, diff, prereq, pr, title in CARDS:
    for p in prereq:
        if p not in order:
            errs.append(f"{cid}: 없는 선행 카드 {p}")
        elif order[p] >= order[cid]:
            errs.append(f"{cid}: 선행 {p} 가 자기보다 뒤에 있다 (전방참조)")
    if pr not in {"P-01", "P-02", "P-03", "P-04", "P-05"}:
        errs.append(f"{cid}: 알 수 없는 원칙 {pr}")
    if not 1 <= diff <= 5:
        errs.append(f"{cid}: 난이도 범위 벗어남")
for ch, *_ in CHAPTERS:
    n = sum(1 for c in CARDS if c[0].startswith(ch + "-"))
    if not 20 <= n <= 26:
        errs.append(f"{ch}: 카드 수 {n} (20~26 밖)")
if errs:
    raise SystemExit("검증 실패:\n  " + "\n  ".join(errs))

